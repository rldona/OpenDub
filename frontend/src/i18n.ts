const dictionaries: Record<Lang, Record<Key, string>> = { en, es };

export function translate(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  return dictionaries[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
